ROLES = ("bg_lo", "bg_hi", "line_lo", "line_hi", "water", "shore", "snow", "warm",
         "rim", "ice", "ink_halo", "ink", "city", "road", "ski", "lift", "border",
         "aurora_a", "aurora_b")


def _hex(h):
    h = h.lstrip("#")
    return tuple(round(int(h[i:i + 2], 16) / 255.0, 3) for i in (0, 2, 4))


def _theme(label, **roles):
    out = {"label": label}
    for r in ROLES:
        v = roles[r]
        out[r] = _hex(v) if isinstance(v, str) else tuple(v)
    return out


