"""Colour themes: the one source of truth.

The engine compiles these in via engine/themes.h, generated by
`python3 -m topopaper.themes > engine/themes.h` (a test keeps the two in
sync). The settings app reads them for its swatches.

Roles:
    bg_lo, bg_hi       background gradient (bottom, top)
    line_lo, line_hi   contour lines, low to high elevation
    water, shore       lake/ocean fill and shoreline stroke
    snow               snow tint above the snowline
    warm               tint the lines take on while the CPU is busy
    rim                glow at the globe's edge
    ice                polar ice caps
    ink_halo, ink      label and HUD text: halo and fill
    city               night-side city lights
    road, ski, lift    pack features (roads, ski runs, ski lifts)
    border             state/province borders
    aurora_a, aurora_b aurora gradient
"""
