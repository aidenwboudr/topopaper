# Packs bake their feature colours into meta.bin using the macchiato values;
# the engine recognises those and swaps in the active theme's role.
BAKED_KEYS = ("road", "ski", "lift", "border")


def c_header():
    out = ["// Generated by `python3 -m topopaper.themes` from topopaper/themes.py.",
           "// Do not edit by hand.", "#pragma once", "",
           f"#define THEME_NROLES {len(ROLES)}",
           "enum { " + ", ".join(f"TR_{r.upper()}" for r in ROLES) + " };",
           "static const char *theme_names[] = { "
           + ", ".join(f'"{n}"' for n in THEMES) + " };",
           f"#define THEME_COUNT {len(THEMES)}",
           "static const float theme_rgb[THEME_COUNT][THEME_NROLES][3] = {"]
    for name, t in THEMES.items():
        out.append(f"    {{ // {name}")
        for r in ROLES:
            c = t[r]
            out.append(f"        {{ {c[0]:.3f}f, {c[1]:.3f}f, {c[2]:.3f}f }}, // {r}")
        out.append("    },")
    out.append("};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.stdout.write(c_header())
